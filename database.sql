CREATE DATABASE IF NOT EXISTS replate CHARACTER SET utf8mb4;
USE replate;
SET FOREIGN_KEY_CHECKS=0;
DROP TABLE IF EXISTS reviews,requests,donations,foods,categories,users;
SET FOREIGN_KEY_CHECKS=1;
CREATE TABLE users(id INT AUTO_INCREMENT PRIMARY KEY,name VARCHAR(120),email VARCHAR(120) UNIQUE,password VARCHAR(255),role ENUM('donor','receiver','volunteer','admin'),location VARCHAR(255),status ENUM('verified','pending','blocked') DEFAULT 'verified',created TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE categories(id INT PRIMARY KEY,name VARCHAR(80),emoji VARCHAR(16));
CREATE TABLE foods(id INT AUTO_INCREMENT PRIMARY KEY,category_id INT,name VARCHAR(120),image VARCHAR(160),INDEX(category_id),FOREIGN KEY(category_id) REFERENCES categories(id));
CREATE TABLE donations(id INT AUTO_INCREMENT PRIMARY KEY,donor_id INT,food_id INT,category_id INT,title VARCHAR(160),qty INT DEFAULT 1,unit VARCHAR(30) DEFAULT 'meals',description TEXT,pickup_location VARCHAR(255),available_from DATETIME NULL,deadline DATETIME NULL,instructions VARCHAR(255),status ENUM('draft','scheduled','available','reserved','completed','cancelled') DEFAULT 'available',created TIMESTAMP DEFAULT CURRENT_TIMESTAMP,FOREIGN KEY(donor_id) REFERENCES users(id),FOREIGN KEY(food_id) REFERENCES foods(id));
CREATE TABLE requests(id INT AUTO_INCREMENT PRIMARY KEY,donation_id INT,receiver_id INT,volunteer_id INT NULL,status ENUM('requested','approved','assigned','picked','delivered','declined') DEFAULT 'requested',code CHAR(4),vol_lat DOUBLE NULL,vol_lng DOUBLE NULL,vol_time DATETIME NULL,created TIMESTAMP DEFAULT CURRENT_TIMESTAMP,FOREIGN KEY(donation_id) REFERENCES donations(id),FOREIGN KEY(receiver_id) REFERENCES users(id));
CREATE TABLE reviews(id INT AUTO_INCREMENT PRIMARY KEY,request_id INT UNIQUE,from_id INT,to_id INT,rating TINYINT,comment VARCHAR(255),created TIMESTAMP DEFAULT CURRENT_TIMESTAMP);
